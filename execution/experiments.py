"""Paired synthetic liquidity-snapshot experiments; no predictive or market-impact model."""
from book import Book
import csv,json,random,statistics,hashlib
from pathlib import Path

def market(seed,steps=20):
    r=random.Random(seed);mid=10000;rows=[]
    for t in range(steps):
        if t: mid+=r.choice([-3,-2,-1,0,1,2,3])
        rows.append({'mid':mid,'depth':[r.randint(5,20) for _ in range(3)],'spread':r.choice([1,2,3])})
    return rows

def execute(rows,policy,parent=100,fee_bps=1,limit_offset=10):
    if policy not in ('immediate','twap'):raise ValueError('unknown policy')
    if not rows or type(parent) is not int or parent<=0 or fee_bps<0 or limit_offset<0:raise ValueError('invalid execution input')
    arrival=rows[0]['mid'];limit=arrival+limit_offset;filled=0;cost=0;fees=0.;trace=[]
    for t,row in enumerate(rows):
        b=Book();m=row['mid']
        for j,depth in enumerate(row['depth']):
            b.apply(dict(type='NEW',ts=t,order_id=f'ask{j}',side='S',price=m+row['spread']+j,qty=depth,tif='GTC'))
        # Cumulative TWAP catches up on missed fills; fixed parent budget prevents overfill.
        target=parent if policy=='immediate' else parent*(t+1)//len(rows)
        qty=max(0,target-filled)
        if qty:
            res=b.apply(dict(type='NEW',ts=t,order_id='parent',side='B',price=limit,qty=qty,tif='IOC'))
            for tr in res['trades']:
                filled+=tr['qty'];cost+=tr['qty']*tr['price'];fees+=tr['qty']*tr['price']*fee_bps/10000
        trace.append({'step':t,'filled':filled,'notional':cost,'fees':fees,'mid':m})
        if filled==parent:break
    unfilled=parent-filled
    opportunity=unfilled*(rows[-1]['mid']-arrival)
    slippage=cost-filled*arrival
    return {'policy':policy,'filled':filled,'fill_rate':filled/parent,'vwap':cost/filled if filled else None,
            'slippage_ticks':slippage,'fees_ticks':fees,'opportunity_ticks':opportunity,
            'implementation_shortfall_bps':(slippage+fees+opportunity)/(parent*arrival)*10000,'trace':trace}

def paired_interval(differences,seed=991,resamples=2000):
    if not differences:raise ValueError('empty differences')
    r=random.Random(seed);n=len(differences)
    means=sorted(statistics.mean(r.choices(differences,k=n)) for _ in range(resamples))
    return {'mean':statistics.mean(differences),'lower_95':means[int(.025*(resamples-1))],'upper_95':means[int(.975*(resamples-1))]}

def main():
    out=Path(__file__).parent/'results';out.mkdir(exist_ok=True);rows=[];diff=[]
    for seed in range(100):
        path=market(seed);a=execute(path,'immediate');b=execute(path,'twap');diff.append(b['implementation_shortfall_bps']-a['implementation_shortfall_bps'])
        for result in [a,b]:rows.append({'seed':seed,**{k:v for k,v in result.items() if k!='trace'}})
    with (out/'execution_trials.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=rows[0]);w.writeheader();w.writerows(rows)
    report={'source':'Synthetic liquidity snapshots generated by experiments.py','source_url':'https://github.com/Anjaney336/quant-execution-lab/blob/main/experiments.py','access_date':'2026-10-24','seeds':100,'policies':2,'paired_twap_minus_immediate_shortfall_bps':paired_interval(diff),'assumptions':{'parent_buy_units':100,'steps':20,'limit_ticks_above_arrival':10,'fees_bps':1,'depth_per_level':[5,20],'levels':3,'mid_step_choices':[-3,-2,-1,0,1,2,3]},'limitations':'Snapshots replenish independently. No persistent market impact, queue model, feedback or empirical calibration. Incomplete execution includes terminal-mid opportunity cost, not forced execution. Bootstrap is conditional on the assumed synthetic generator.','trials_sha256':hashlib.sha256((out/'execution_trials.csv').read_bytes()).hexdigest()}
    (out/'execution_analysis.json').write_text(json.dumps(report,indent=2));print(json.dumps(report,indent=2))
if __name__=='__main__':main()

"""Fictional household goal-funding study. Assumptions, not investment advice."""
from pathlib import Path
import json,csv,hashlib
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

POLICIES={'defensive':[.25,.55,.10,.10],'balanced':[.50,.30,.15,.05],'growth':[.70,.15,.10,.05]}
ASSETS=['Equity','Bonds','Listed REIT','Cash']
CORR=np.array([[1,.1,.65,0],[.1,1,.15,0],[.65,.15,1,0],[0,0,0,1]])

def paths(seed=20261024,n=2000,years=10):
    rng=np.random.default_rng(seed)
    mu=np.array([.08,.045,.065,.03]);vol=np.array([.20,.06,.18,.005])
    z=rng.normal(size=(n,years,4))@np.linalg.cholesky(CORR).T
    return np.exp(mu-.5*vol**2+z*vol)-1

def evaluate(returns,weights,initial=2_000_000,contribution=240_000,goal_real=5_000_000,inflation=.05,fee=.005,cost=.001):
    r=np.asarray(returns,dtype=float);w=np.asarray(weights,dtype=float)
    if r.ndim!=3 or r.shape[2]!=4 or r.shape[1]<1 or not np.isfinite(r).all() or (r<=-1).any():raise ValueError('finite asset returns above -100% required')
    if w.shape!=(4,) or not np.isfinite(w).all() or (w<0).any() or not np.isclose(w.sum(),1):raise ValueError('long-only fully invested weights required')
    if not np.isfinite([initial,contribution,goal_real,inflation,fee,cost]).all() or min(initial,contribution,goal_real,cost)<0 or not 0<=fee<1 or not 0<=cost<1 or inflation<=-1:raise ValueError('invalid economics')
    n,years,_=r.shape;holdings=np.tile(initial*w,(n,1));history=[holdings.sum(axis=1)];fees=np.zeros(n);trading=np.zeros(n)
    for t in range(years):
        grown=holdings*(1+r[:,t]);gross=grown.sum(axis=1);charge=gross*fee;fees+=charge
        net=grown*(1-fee);total=net.sum(axis=1)+contribution
        # Contribution enters cash; fee is paid before reallocation. Solve circular
        # post-cost target wealth by bisection, with cost on gross traded notional.
        before=net.copy();before[:,3]+=contribution
        lo=np.zeros(n);hi=total.copy()
        for _ in range(60):
            mid=(lo+hi)/2;trade=cost*np.abs(mid[:,None]*w-before).sum(axis=1)
            high=mid+trade>total;hi=np.where(high,mid,hi);lo=np.where(high,lo,mid)
        wealth=(lo+hi)/2;tc=cost*np.abs(wealth[:,None]*w-before).sum(axis=1)
        if np.max(np.abs(wealth+tc-total))>1e-6:raise ArithmeticError('cash reconciliation')
        holdings=wealth[:,None]*w;trading+=tc;history.append(wealth)
    terminal=holdings.sum(axis=1)/(1+inflation)**years;shortfall=np.maximum(goal_real-terminal,0)
    return dict(real_terminal=terminal,history=np.array(history).T,summary=dict(funding_probability=float(np.mean(terminal>=goal_real)),median_real_terminal=float(np.median(terminal)),p05_real_terminal=float(np.quantile(terminal,.05)),mean_real_shortfall=float(shortfall.mean()),mean_management_fees=float(fees.mean()),mean_rebalance_cost=float(trading.mean())))

def main():
    out=Path(__file__).parent/'results';r=paths();results={};rows=[];histories={}
    for name,w in POLICIES.items():
        base=evaluate(r,w);results[name]={'weights':w,'base':base['summary']};histories[name]=base['history']
        for stress in ['early_loss','late_loss','high_inflation']:
            x=r.copy()
            if stress!='high_inflation':x[:,0 if stress=='early_loss' else -1,:]=[-.35,-.08,-.30,.02]
            results[name][stress]=evaluate(x,w,inflation=.07 if stress=='high_inflation' else .05)['summary']
        for i,v in enumerate(base['real_terminal']):rows.append(dict(policy=name,path=i,real_terminal=v,shortfall=max(5_000_000-v,0)))
    with (out/'wealth_trials.csv').open('w',newline='') as f:
        wr=csv.DictWriter(f,fieldnames=rows[0]);wr.writeheader();wr.writerows(rows)
    report=dict(source={'name':'Synthetic multivariate lognormal annual returns generated by wealth_policy.py','url':'https://github.com/Anjaney336/integrated-real-assets-research/blob/main/wealth_policy.py','access_date':'2026-10-24','seed':20261024},
        assumptions={'paths':2000,'years':10,'initial_inr':2000000,'annual_nominal_contribution_inr':240000,'goal_today_inr':5000000,'inflation':.05,'management_fee':.005,'gross_turnover_cost':.001,'assets':ASSETS,'log_return_drift':[.08,.045,.065,.03],'volatility':[.20,.06,.18,.005],'correlation':CORR.tolist(),'cashflow_order':'asset returns; fee; year-end cash contribution; rebalance after trading cost'},
        results=results,limits='Fictional household, assumed uncalibrated returns/correlations and constant inflation. No tax, withdrawals, default, illiquidity, changing correlations or household property exposure. Probability is simulation frequency, not a forecast. Emergency reserve is excluded from investable initial wealth; no client suitability assessment performed.',
        trial_sha256=hashlib.sha256((out/'wealth_trials.csv').read_bytes()).hexdigest())
    (out/'wealth_summary.json').write_text(json.dumps(report,indent=2))
    fig,axes=plt.subplots(1,2,figsize=(11,4.5))
    for name,h in histories.items():
        real=h/(1.05**np.arange(11))[None,:]/1e6
        axes[0].plot(range(11),np.median(real,axis=0),label=name)
    axes[0].axhline(5,color='black',ls='--',label='10-year goal');axes[0].set(xlabel='Year',ylabel='Median wealth in today’s INR million',title='Contributions included; not investment-return curves');axes[0].legend()
    labels=list(POLICIES);xx=np.arange(3)
    for i,case in enumerate(['base','early_loss','late_loss','high_inflation']):axes[1].bar(xx+(i-1.5)*.19,[results[n][case]['funding_probability'] for n in labels],width=.19,label=case)
    axes[1].set(xticks=xx,xticklabels=labels,ylim=(0,1),ylabel='Simulated goal-funding frequency',title='Same paths; explicit adverse scenarios');axes[1].legend(fontsize=8)
    fig.tight_layout();fig.savefig(out/'wealth_policy.svg');plt.close(fig)
    print(json.dumps(results,indent=2))

if __name__=='__main__':main()
